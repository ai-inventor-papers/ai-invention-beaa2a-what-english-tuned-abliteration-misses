#!/usr/bin/env python3
"""results/report_tables.md: every table the README and the paper quote, printed straight from
results/analysis_summary.json + results/redundancy_index.json (no number is typed by hand)."""
from __future__ import annotations

import os

for _v in ("OPENBLAS_NUM_THREADS", "OMP_NUM_THREADS"):
    os.environ.setdefault(_v, "4")

import numpy as np

import common as C
from common import jload


def f(x, n=2):
    return "–" if x is None or (isinstance(x, float) and np.isnan(x)) else f"{x:.{n}f}"


def ci(x, n=2):
    return "" if not x or any(v is None or np.isnan(v) for v in x) else f" [{x[0]:.{n}f}, {x[1]:.{n}f}]"


def main() -> None:
    S = jload(C.RES / "analysis_summary.json")
    T = S["cell_table"]
    ri = jload(C.RES / "redundancy_index.json") if (C.RES / "redundancy_index.json").exists() else None
    L = []
    L.append("# Tables (generated by report_tables.py from analysis_summary.json)\n")
    L.append(f"Primary judge: **{S['judge_primary']}**; judged coverage "
             + ", ".join(f"{k} {v:.0%}" for k, v in S["judged_coverage"].items()) + ".\n")

    if ri:
        L.append("\n## A. DEV depth-redundancy index (activation arms, S3 half A, "
                 f"n={ri['n_items']} harmful items per language)\n")
        L.append(f"index_EN = **{ri['index']['en']}** (95% CI {ri['index_boot_CI95']['en']}), "
                 f"index_SL = **{ri['index']['sl']}** (95% CI {ri['index_boot_CI95']['sl']}), "
                 f"difference SL−EN = {ri['diff_SL_minus_EN']} (CI {ri['diff_boot_CI95']}), "
                 f"pre-declared equivalence margin ±8.\n")
        ks = sorted(int(k) for k in ri["prefix_curves"]["en"])
        L.append("\n| cumulative prefix | " + " | ".join(f"P{k}" for k in ks) + " |")
        L.append("|---|" + "---|" * len(ks))
        for g in ("en", "sl"):
            L.append(f"| {g.upper()} judged refusal | " +
                     " | ".join(f(ri['prefix_curves'][g].get(str(k), ri['prefix_curves'][g].get(k))) for k in ks) + " |")
        L.append(f"\nUnedited (no-op): EN {f(ri['noop_refusal']['en'])}, SL {f(ri['noop_refusal']['sl'])}. "
                 f"Curve AUC: EN {f(ri['prefix_AUC']['en'])}{ci(ri['prefix_AUC_CI95']['en'])}, "
                 f"SL {f(ri['prefix_AUC']['sl'])}{ci(ri['prefix_AUC_CI95']['sl'])}.\n")
        L.append("\n### Leave-one-band-out necessity (Δ vs ablating all 48) and suffix curves\n")
        L.append("| arm | EN | SL |\n|---|---|---|")
        for k in sorted(ri["lobo_necessity_vs_all48"]["en"]):
            L.append(f"| {k} | {f(ri['lobo_necessity_vs_all48']['en'][k])} | {f(ri['lobo_necessity_vs_all48']['sl'][k])} |")
        for k in sorted(ri["suffix_curves"]["en"]):
            L.append(f"| {k} (suffix, absolute) | {f(ri['suffix_curves']['en'][k])} | {f(ri['suffix_curves']['sl'][k])} |")
        L.append("\n### DEV arm collateral\n")
        L.append("| arm | EN ref | SL ref | SL PARTIAL | SL INVALID | SL wrong-lang | EN ΔNLL | SL ΔNLL |\n|---|---|---|---|---|---|---|---|")
        for a, r in ri["arm_table"].items():
            L.append(f"| {a.replace('dev_','')} | {f(r['en_REFUSED'])} | {f(r['sl_REFUSED'])} | {f(r['sl_PARTIAL'])} | "
                     f"{f(r['sl_INVALID'])} | {f(r['sl_wrong_lang'])} | {f(r['en_flores_dNLL'],3)} | {f(r['sl_flores_dNLL'],3)} |")

    L.append("\n## B. Weight-edit cells (Part B)\n")
    L.append("| cell | tier | E | layers | EN ref (screen) | SL ref (screen) | SL ref (confirm) | SL PARTIAL | SL INVALID | "
             "SL ΔNLL | SL MC | degraded |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for cell, r in sorted(T.items(), key=lambda kv: (kv[1].get("tier") or "Z", kv[0])):
        if r.get("tier") is None or cell.startswith("dev_"):
            continue
        sc_sl = f(r.get("screen_sl_REFUSED")) + ci(r.get("screen_sl_REFUSED_ci"))
        cf_sl = f(r.get("confirm_sl_REFUSED")) + ci(r.get("confirm_sl_REFUSED_ci"))
        L.append(f"| {cell} | {r.get('tier')} | {f(r.get('E_exact'),1)} | {r.get('n_layers')} | "
                 f"{f(r.get('screen_en_REFUSED'))} | {sc_sl} | {cf_sl} | {f(r.get('confirm_sl_PARTIAL') or r.get('screen_sl_PARTIAL'))} | "
                 f"{f(r.get('confirm_sl_INVALID') or r.get('screen_sl_INVALID'))} | {f(r.get('flores_dNLL_sl'),3)} | "
                 f"{f(r.get('mc_acc_sl'))} | {','.join(r.get('degraded', [])) or '–'} |")

    P = S.get("frozen_predictions_result", {})
    L.append("\n## C. Frozen predictions\n")
    L.append("| id | result | verdict | Holm p |\n|---|---|---|---|")
    hp = S.get("holm_adjusted_p", {})
    if "PA1" in P:
        a = P["PA1"]
        L.append(f"| PA1 equivalence | index_SL−index_EN = {a['diff']}, CI{ci(a['diff_CI95'],1)}, margin ±{a['margin']} | "
                 f"{a['verdict']} | {f(hp.get('PA1'),3)} |")
    if "PB1" in P:
        a = P["PB1"]
        L.append(f"| PB1 coverage ΔR² | ΔR² = {f(a['dR2'],3)} CI{ci(a['dR2_cell_boot_CI95'],3)} (R² {f(a['R2_base'],3)} → "
                 f"{f(a['R2_full'],3)}, n={a['n_cells']} cells) | {a['verdict']} | {f(hp.get('PB1'),3)} |")
    if "PB2" in P:
        a = P["PB2"]["pooled_narrow_minus_broad"]
        L.append(f"| PB2 narrow−broad at matched E (SL) | {f(a['sl']['diff'])} CI{ci(a['sl']['ci'],3)} (n={a['sl']['n']} items) | "
                 f"{P['PB2']['verdict']} | {f(hp.get('PB2'),3)} |")
        L.append(f"| &nbsp;&nbsp;same, EN | {f(a['en']['diff'])} CI{ci(a['en']['ci'],3)} | – | – |")
    if "PB3" in P:
        a = P["PB3"]
        L.append(f"| PB3 coverage×language | {f(a['interaction_SL_minus_EN'])} CI{ci(a['ci'],3)} | {a['verdict']} | {f(hp.get('PB3'),3)} |")
    if "PB4" in P:
        a = P["PB4"]
        L.append(f"| PB4 out-of-sample index | Spearman {f(a['spearman'])} (n={a['n']}), threshold pass "
                 f"{f(a['threshold_check_pass_rate'])} of {a['threshold_check_n']} | {a['verdict']} | {f(hp.get('PB4'),3)} |")

    if "PB2" in P:
        L.append("\n### Matched-energy groups (each group: same total removal energy)\n")
        L.append("| group | E* | SL narrow | SL broad | SL Δ(narrow−broad) | SL cut(broad vs no-op) | SL cut(random control) | EN Δ |")
        L.append("|---|---|---|---|---|---|---|---|")
        for g, e in P["PB2"]["groups"].items():
            L.append(f"| {g} | {f(e['E_target'],1)} | {f(e['sl_narrow_rate'])} | {f(e['sl_broad_rate'])} | "
                     f"{f(e['sl']['diff'])}{ci(e['sl']['ci'])} | {f(e.get('sl_cut_broad',{}).get('diff'))}"
                     f"{ci(e.get('sl_cut_broad',{}).get('ci'))} | {f(e.get('sl_cut_random',{}).get('diff'))}"
                     f"{ci(e.get('sl_cut_random',{}).get('ci'))} | {f(e['en']['diff'])}{ci(e['en']['ci'])} |")

    dec = (P.get("PB1") or {}).get("decomposition")
    if dec:
        L.append("\n### Where the variance in the Slovene residual sits (nested R², same cells)\n")
        L.append("| model | R² |\n|---|---|")
        for k in ("R2_logE", "R2_logE_plus_placement_b3", "R2_logE_plus_count", "R2_logE_plus_count_and_span"):
            L.append(f"| {k.replace('R2_', '').replace('_', ' ')} | {f(dec[k],3)} |")
        L.append(f"\n{dec['note']}\n")

    pl = S.get("contiguous_vs_spread_matched_count_and_energy", {})
    if pl:
        L.append("\n### Placement at matched energy AND matched layer count (12 contiguous layers vs every 4th layer)\n")
        L.append("| contrast | E | SL band | SL stride-4 | SL Δ(band−stride) | EN band | EN stride-4 | EN Δ |")
        L.append("|---|---|---|---|---|---|---|---|")
        for k, r in pl.items():
            L.append(f"| {k} | {f(r['energy'],1)} | {f(r['sl_band_rate'])} | {f(r['sl_stride_rate'])} | "
                     f"{f(r['sl']['diff'])}{ci(r['sl']['ci'])} | {f(r['en_band_rate'])} | {f(r['en_stride_rate'])} | "
                     f"{f(r['en']['diff'])}{ci(r['en']['ci'])} |")
        L.append("\nBoth arms edit 12 of 48 layers with the same total removal energy; only the placement differs.\n")

    cmp_ = jload(C.RES / "cross_model.json") if (C.RES / "cross_model.json").exists() else None
    if cmp_ and cmp_.get("gemma_sibling_pod"):
        g3, gm = cmp_["gams3"], cmp_["gemma_sibling_pod"]
        L.append("\n## E. Cross-model depth table (descriptive, n = 2 sibling checkpoints)\n")
        L.append("| model | index_EN | index_SL | index_EN CI | index_SL CI | n/lang |\n|---|---|---|---|---|---|")
        L.append(f"| cjvt/GaMS3-12B-Instruct (this pod) | {g3['index']['en']} | {g3['index']['sl']} | "
                 f"{g3['index_CI95']['en']} | {g3['index_CI95']['sl']} | {cmp_['gams3']['source'].split('n=')[-1].split('/')[0] if 'n=' in cmp_['gams3']['source'] else '40'} |")
        L.append(f"| google/gemma-3-12b-it (sibling pod) | {gm['index'].get('en')} | {gm['index'].get('sl')} | "
                 f"{gm['index_CI95'].get('en')} | {gm['index_CI95'].get('sl')} | {gm.get('n_items_per_language')} |")
        L.append(f"\n{cmp_['joint_reading']['statement']}\n\n*{cmp_['joint_reading']['caution']}*\n")

    js = S.get("judge_sensitivity", {})
    if js:
        L.append("\n## D. Judge / label-source sensitivity\n")
        L.append(f"Cohen κ (refused vs not) local Qwen3-14B against gpt-4.1 on doubly labelled items: "
                 f"EN {f(js.get('kappa_en'))} (n={js.get('n_en')}), SL {f(js.get('kappa_sl'))} (n={js.get('n_sl')}); "
                 f"within edited cells {f(js.get('kappa_within_edited'))} (n={js.get('n_within_edited')}).")
        cp = jload(C.RES / "judge_cert_pool.json") if (C.RES / "judge_cert_pool.json").exists() else None
        if cp:
            L.append(f"\nOn-disk certification pool (iteration-2 EDITED arms, n={cp['n']}): κ EN "
                     f"{f(cp['kappa_refused_vs_not_en'])} (n={cp['n_en']}), κ SL {f(cp['kappa_refused_vs_not_sl'])} "
                     f"(n={cp['n_sl']}), κ 4-way SL {f(cp['kappa_4way_sl'])}; the local judge is systematically stricter in "
                     f"English (refused rate {f(cp['rate_refused_local_en'])} vs gpt-4.1 {f(cp['rate_refused_g41_en'])}).")
        L.append(f"\nOpener-rule agreement with the primary judge: {f(S.get('rule_vs_judge',{}).get('agreement'))}.")
    (C.RES / "report_tables.md").write_text("\n".join(L) + "\n")
    print(f"wrote {C.RES / 'report_tables.md'} ({len(L)} lines)")


if __name__ == "__main__":
    main()
