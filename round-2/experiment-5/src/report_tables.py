#!/usr/bin/env python3
"""Render every results table (markdown) directly from the saved result files -> results/analysis/tables.md.
The README and the paper copy numbers from this file only (so text and files cannot disagree).
Usage: .venv/bin/python report_tables.py"""
from __future__ import annotations

import numpy as np

import common as C
from common import MODELS, jload

NAME = {"gams": "GaMS3-12B-Instruct", "gemma": "gemma-3-12b-it"}


def f(x, d=3):
    if x is None:
        return "–"
    try:
        x = float(x)
    except (TypeError, ValueError):
        return str(x)
    return "–" if not np.isfinite(x) else f"{x:.{d}f}"


def pc(x, d=1):
    return "–" if x is None or not np.isfinite(float(x)) else f"{100 * float(x):.{d}f}"


def cis(c, d=3, scale=1.0):
    return "–" if not c or any(v is None for v in c) else f"[{float(c[0]) * scale:.{d}f}, {float(c[1]) * scale:.{d}f}]"


def main() -> None:
    S = jload(C.RES / "analysis" / "summary.json")
    L = []
    add = L.append
    add(f"# Result tables (generated by report_tables.py from results/; label source = {S.get('label_source')})\n")
    # ---------------- behaviour
    gv = S["generation_validity"]
    add("## T1 Harmful S4 behaviour (257 items per model x checkpoint x language)\n")
    add("gpt-4.1 = frozen primary judge on a random ~52% subsample (run budget exhausted); combined = gpt-4.1 where judged, else the "
        "second-family free judge (nvidia/nemotron-3-ultra-550b-a55b:free); markers = Heretic+SL keyword rule on all 257.\n")
    add("| model | ckpt | lang | n gpt-4.1 | refused % [95% CI] | complied % [95% CI] | partial/irrel./malf. % | n combined | combined refused % | combined complied % [95% CI] | marker refusal % | other-language replies % |")
    add("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for m in MODELS:
        for ck in ("orig", "edit"):
            for lang in C.LANGS:
                v = gv.get(f"{m}|{ck}|s4_harmful|{lang}")
                if not v:
                    continue
                oth = sum(v.get(f"judge_{k}", 0) for k in ("partial", "irrelevant", "malformed", "empty"))
                add(f"| {NAME[m]} | {ck} | {lang.upper()} | {v.get('n_judged')} | {pc(v.get('judge_refused', np.nan))} {cis(v.get('judge_refused_ci95'), 1, 100)} | "
                    f"{pc(v.get('judge_complied', np.nan))} {cis(v.get('judge_complied_ci95'), 1, 100)} | {pc(oth)} | {v.get('n_combined')} | "
                    f"{pc(v.get('combined_refused', np.nan))} | {pc(v.get('combined_complied', np.nan))} {cis(v.get('combined_complied_ci95'), 1, 100)} | "
                    f"{pc(v['kw_refusal'])} | {pc(v['other_study_lang'])} |")
    ja = S.get("judge_agreement", {})
    add(f"\nJudge agreement (second judge vs gpt-4.1, stratified sample n={ja.get('n_second')}): 6-way kappa {f(ja.get('kappa_6way_j1_j2'))}, "
        f"refused-vs-not kappa {f(ja.get('kappa_refused_j1_j2'))}, raw agreement {f(ja.get('agreement_j1_j2'))}; "
        f"marker rule vs gpt-4.1 (refused) kappa {f(ja.get('kappa_refused_j1_markers'))}.\n")
    cov = S.get("label_coverage", {})
    if cov:
        add("Label coverage (generations with a gpt-4.1 label / with only a second-judge label / total):\n")
        add("| model / kind / ckpt | gpt-4.1 | second judge only | n |")
        add("|---|---|---|---|")
        for k, v in sorted(cov.items()):
            add(f"| {k} | {v['gpt41']} | {v['judge2']} | {v['n']} |")
        add("")
    # ---------------- harmless
    add("## T2 Held-out harmless S4 twins: divergence and output validity (128-token generations)\n")
    add("| model | ckpt | lang | KL1 median [95% CI] | KL32 median [95% CI] | KL1 mean | benign refusal % (combined judge, n) | marker refusal % | other-language % | GlotLID wrong % | rep4 mean | malformed % | empty % |")
    add("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for m in MODELS:
        dv = S["models"].get(m, {}).get("divergence", {})
        for ck in ("orig", "edit"):
            for lang in C.LANGS:
                v = gv.get(f"{m}|{ck}|s4_harmless|{lang}")
                if not v:
                    continue
                k = dv.get(f"harmless|{lang}", {})
                kl1 = f"{f(k['KL1']['median'], 4)} {cis(k['KL1']['median_ci95'], 4)}" if ck == "edit" and k else "0 (reference)"
                kl32 = f"{f(k['KL32']['median'], 4)} {cis(k['KL32']['median_ci95'], 4)}" if ck == "edit" and k else "0"
                klm = f(k["KL1"]["mean"], 4) if ck == "edit" and k else "0"
                add(f"| {NAME[m]} | {ck} | {lang.upper()} | {kl1} | {kl32} | {klm} | {pc(v.get('combined_refused', np.nan))} ({v.get('n_combined')}) | "
                    f"{pc(v['kw_refusal'])} | {pc(v['other_study_lang'])} | {pc(v['wrong_lang'])} | {f(v['rep4_mean'])} | {pc(v['malformed_rule'])} | {pc(v['empty'])} |")
    # ---------------- utility
    add("\n## T3 Utility (0-shot, 250 frozen items per task and language, NF4; paired item bootstrap 95% CI, points)\n")
    add("| model | lang | task (metric) | original | edited | change [95% CI] | items up / down |")
    add("|---|---|---|---|---|---|---|")
    for m in MODELS:
        u = S["models"].get(m, {}).get("utility", {})
        for lang in C.LANGS:
            if lang not in u:
                continue
            for t in C.TASKS + ["macro"]:
                v = u[lang][t]
                ud = f"{v['n_flip_up']} / {v['n_flip_down']}" if t != "macro" else f"p_boot {f(v['p_boot_two_sided'])}"
                met = v.get("metric", "mean of task metrics")
                add(f"| {NAME[m]} | {lang.upper()} | {t} ({met}) | {pc(v['orig'])} | {pc(v['edit'])} | {pc(v['delta'], 2)} {cis(v['delta_ci95'], 2, 100)} | {ud} |")
    hol = S.get("family_U_holm", {})
    add("\nConfirmatory family U (Holm over 4 macro changes): " + "; ".join(f"{k}: p={f(v['p'])}, p_Holm={f(v['p_holm'])}" for k, v in hol.items()))
    add("\n## T4 FLORES+ devtest per-token NLL (1012 sentences per language)\n")
    add("| model | lang | NLL original | NLL edited | change [95% CI] |")
    add("|---|---|---|---|---|")
    for m in MODELS:
        fl = S["models"].get(m, {}).get("flores", {})
        for lang in C.LANGS:
            if lang in fl:
                v = fl[lang]
                add(f"| {NAME[m]} | {lang.upper()} | {f(v['nll_orig'], 4)} | {f(v['nll_edit'], 4)} | {f(v['delta'], 4)} {cis(v['delta_ci95'], 4)} |")
    # ---------------- mechanistic
    add("\n## T5 Bilingual harm geometry in the ORIGINAL models (primary site; S3 = DEV, S4 = held-out)\n")
    add("| model | layer | cos(d_EN,d_SL) raw | split-half ceiling EN/SL | corrected | S3 CV AUROC DiM EN/SL | S3 CV AUROC LR EN/SL | TF-IDF lexical EN/SL | length-only EN/SL | length-residualized DiM EN/SL | EN->SL / SL->EN transfer (S4) | S4 held-out frozen DiM EN/SL | hoc stratum EN/SL | cos(lang dir, d_EN) | shuffled-label AUROC |")
    add("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for m in MODELS:
        mp = S["models"].get(m, {}).get("mech_primary")
        if not mp:
            continue
        p, c3, h = mp["profile_at_primary"], mp["S3_controls"], mp["S4_heldout_orig"]
        add(f"| {NAME[m]} | {MODELS[m]['primary_layer']} | {f(p['cos_raw'])} | {f(p['ceil_en'])}/{f(p['ceil_sl'])} | {f(p['cos_corr'])} | "
            f"{f(c3['en']['cv_dim']['auc'])}/{f(c3['sl']['cv_dim']['auc'])} | {f(c3['en']['cv_lr']['auc'])}/{f(c3['sl']['cv_lr']['auc'])} | "
            f"{f(c3['en']['tfidf_lexical']['auc'])}/{f(c3['sl']['tfidf_lexical']['auc'])} | {f(c3['en']['length_only'])}/{f(c3['sl']['length_only'])} | "
            f"{f(c3['en']['dim_length_residualized'])}/{f(c3['sl']['dim_length_residualized'])} | {f(p['tr_en2sl_S4'])}/{f(p['tr_sl2en_S4'])} | "
            f"{f(h['en']['frozen_dim']['auc'])}/{f(h['sl']['frozen_dim']['auc'])} | {f(h['en']['frozen_dim_hoc']['auc'])}/{f(h['sl']['frozen_dim_hoc']['auc'])} | "
            f"{f(p['cos_lang_dEN'])} | {f(mp['T3']['halfB_shuffled_label_auc']['auc'])} |")
    add("\n## T6 Frozen original probe vs refit probe, before and after the edit (S4, primary site; item-cluster bootstrap)\n")
    add("| model | lang | variant | probe | frozen orig AUROC | frozen edit - orig [95% CI] | refit orig AUROC | refit edit - orig [95% CI] | refit share of frozen drop | pre-registered class |")
    add("|---|---|---|---|---|---|---|---|---|---|")
    for m in MODELS:
        mech = C.RES / m / f"mech_{m}.json"
        if not mech.exists():
            continue
        fr = jload(mech)["primary"]["frozen_vs_refit"]
        for key, v in fr.items():
            var, lang = key.split("|")
            for pr in ("dim", "lr"):
                x = v[pr]
                fd, rd = x["frozen_edit_minus_orig"]["diff_vs_2"], x["refit_edit_minus_orig"]["diff_vs_2"]
                share = f(rd / fd, 3) if abs(fd) > 1e-3 else "–"
                add(f"| {NAME[m]} | {lang.upper()} | {var} | {pr} | {f(x['frozen_orig']['auc'])} | {f(fd)} {cis(x['frozen_edit_minus_orig']['diff_ci95'])} | "
                    f"{f(x['refit_orig']['auc'])} | {f(rd)} {cis(x['refit_edit_minus_orig']['diff_ci95'])} | {share} | {x['class']} |")
    add("\nAll-layer profile (DiM, pos -1): minimum frozen-probe AUROC on EDITED activations over layers, and refit AUROC at that layer.\n")
    add("| model | lang | min frozen-edit AUROC (layer) | refit-edit AUROC there | max relative activation shift ||mean edit - mean orig|| / ||mean orig|| (layer) |")
    add("|---|---|---|---|---|")
    for m in MODELS:
        p = C.RES / m / f"layer_profiles_{m}.npz"
        if not p.exists():
            continue
        P = np.load(p)
        for lang in C.LANGS:
            fe = P[f"s4_frozen_edit_{lang}"].copy()
            fe[0] = np.nan
            i = int(np.nanargmin(fe))
            sh = P[f"shift_norm_{lang}"] / np.maximum(P[f"orig_norm_{lang}"], 1e-9)
            j = int(np.nanargmax(sh))
            add(f"| {NAME[m]} | {lang.upper()} | {f(fe[i])} (L{i}) | {f(P[f's4_refit_edit_{lang}'][i])} | {f(sh[j])} (L{j}) |")
    add("\n## T7 Drift geometry at the primary site (exploratory; S4 harmful vs harmless twins)\n")
    add("| model | lang | Cohen d on frozen axis orig -> edit | share of mean-difference energy on frozen axis orig -> edit | cos(refit axis orig, refit axis edit) | Cohen d on Heretic dir orig -> edit | AUROC with frozen axis projected out orig -> edit | collapse onset layer |")
    add("|---|---|---|---|---|---|---|---|")
    for m in MODELS:
        dgp = C.RES / m / f"drift_geometry_{m}.json"
        if not dgp.exists():
            continue
        dg = jload(dgp)
        for lang in C.LANGS:
            v = dg["primary"][lang]
            add(f"| {NAME[m]} | {lang.upper()} | {f(v['sep_frozen_orig']['value'], 2)} -> {f(v['sep_frozen_edit']['value'], 2)} {cis(v['sep_frozen_edit']['ci95'], 2)} | "
                f"{f(v['frac_on_frozen_orig']['value'])} -> {f(v['frac_on_frozen_edit']['value'])} | {f(v['cos_refit_orig_edit']['value'])} {cis(v['cos_refit_orig_edit']['ci95'])} | "
                f"{f(v['sep_heretic_orig']['value'], 2)} -> {f(v['sep_heretic_edit']['value'], 2)} | {f(v['auc_compl_frozen_orig'])} -> {f(v['auc_compl_frozen_edit'])} | "
                f"{dg['collapse_onset_layer'].get(lang)} |")
        sh = dg.get("harmful_shift_along_heretic_dir_in_orig_sd_units", {})
        if sh:
            add(f"\n{NAME[m]}: mean shift of HARMFUL items along Heretic's direction (orig-SD units) by layer: " +
                "; ".join(f"{lang.upper()} " + ", ".join(f"{k} {f(v, 2)}" for k, v in sh[lang].items() if int(k[1:]) % 8 == 0 or int(k[1:]) == MODELS[m]['primary_layer'])
                          for lang in C.LANGS) + "\n")
    # ---------------- gate + A2
    add("\n## T8 Readout validity gate (gpt-4.1 judged S4 items, orig+edit; refused vs complied only)\n")
    add("| model | lang | n used (excluded) | R_seq item AUROC | R_seq 16-cell Spearman | R_seq pass | R1 item AUROC | R1 16-cell Spearman | R1 pass | primary trait |")
    add("|---|---|---|---|---|---|---|---|---|---|")
    for m in MODELS:
        g = S["models"].get(m, {}).get("gate", {})
        for lang in C.LANGS:
            if lang not in g:
                continue
            v = g[lang]
            add(f"| {NAME[m]} | {lang.upper()} | {v['n_items'] - v['n_excluded']} ({v['n_excluded']}) | {f(v['R_seq'].get('item_auroc'))} | {f(v['R_seq'].get('cond_spearman_16cells'))} | "
                f"{v['R_seq'].get('pass')} | {f(v['R1'].get('item_auroc'))} | {f(v['R1'].get('cond_spearman_16cells'))} | {v['R1'].get('pass')} | {v['primary_trait']} |")
    add("\n## T9 A2 criterion shift vs evidence loss (x = ORIGINAL-model frozen DiM score, standardized; item-cluster bootstrap)\n")
    add("| model | readout | lang | b0 (pre) | b1 (post) | slope ratio [90% CI] | intercept shift [95% CI] | harmful-only ratio [90% CI] | U-projected x ratio | post-edit-score x ratio | judged logistic ratio [90% CI] | s:post:lang [90% CI] | decision |")
    add("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for m in MODELS:
        a2 = S["models"].get(m, {}).get("A2", {})
        for R in ("R_seq", "R1"):
            if R not in a2:
                continue
            for lang in C.LANGS:
                v = a2[R]["per_lang"][lang]
                p = v["primary"]
                lg = v.get("logistic_judged", {})
                lgs = f"{f(lg.get('slope_ratio'))} {cis(lg.get('slope_ratio_ci90'))}" if lg.get("computable") else "n/c"
                add(f"| {NAME[m]} | {R} | {lang.upper()} | {f(p['b0'])} | {f(p['b1'])} | {f(p['slope_ratio'])} {cis(p['slope_ratio_ci90'])} | "
                    f"{f(p['intercept_shift'])} {cis(p['intercept_shift_ci95'])} | {f(v['harmful_only']['slope_ratio'])} {cis(v['harmful_only']['slope_ratio_ci90'])} | "
                    f"{f(v['U_projected_score']['slope_ratio'])} | {f(v['post_edit_score_regressor']['slope_ratio'])} | {lgs} | "
                    f"{f(a2[R]['interaction_s_post_lang']['s_post_lang'])} {cis(a2[R]['interaction_s_post_lang']['ci90'])} | {a2[R]['decision']} |")
        if a2:
            add(f"\n{NAME[m]}: pre-registered readout = {a2.get('pre_registered_readout')}; decision = {a2.get('decision_preregistered')}\n")
    add("\n## T10 r_prior (harmless-refusal direction, orthogonalized to d_EN; ORIGINAL r_prior generations)\n")
    for m in MODELS:
        rp = S["models"].get(m, {}).get("r_prior", {})
        if rp:
            Lp = MODELS[m]["primary_layer"]
            txt = f"- {NAME[m]}: n refused {rp.get('n_refused')} (EN {rp.get('n_refused_by_lang', {}).get('en')}, SL {rp.get('n_refused_by_lang', {}).get('sl')}), complied {rp.get('n_complied')}; defined {rp.get('defined')}"
            for tag in ("pooled", "withinSL", "withinEN"):
                if f"{tag}_cos_with_lang_dir" in rp:
                    txt += f"; {tag}: cos(r_prior, lang_dir) at L{Lp} = {f(rp[f'{tag}_cos_with_lang_dir'][Lp])}, cos(r, d_EN) before orth. = {f(rp[f'{tag}_cos_with_dEN_before_orth'][Lp])}"
            add(txt)
    add("\n## T11 Item-level flips (harmful items refused by the original; exploratory)\n")
    add("| model | labels | lang | n refused by orig (used) | flip rate | AUROC s_frozen_orig | AUROC her_orig | AUROC edit shift on Heretic dir | AUROC edit shift on frozen axis | AUROC relative shift norm | AUROC R_seq_orig (low) |")
    add("|---|---|---|---|---|---|---|---|---|---|---|")
    for m in MODELS:
        for key, lab in (("flip_analysis", "gpt-4.1"), ("flip_analysis_markers", "markers")):
            fa = S["models"].get(m, {}).get(key, {})
            for lang in C.LANGS:
                if lang not in fa:
                    continue
                v = fa[lang]
                g = lambda c: f"{f(v[c]['auc'])} {cis(v[c]['ci95'], 2)}" if c in v else "–"  # noqa: E731
                add(f"| {NAME[m]} | {lab} | {lang.upper()} | {v['n_orig_refused']} ({v['n_used']}) | {pc(v['flip_rate'])} | {g('auroc_s_frozen_orig')} | {g('auroc_her_orig')} | "
                    f"{g('auroc_d_her')} | {g('auroc_d_fz')} | {g('auroc_shiftnorm')} | {g('auroc_R_seq_orig')} |")
    # ---------------- dose
    add("\n## T12 Exploratory edit-strength dose-response (LoRA delta x f; f=1 is the core edit)\n")
    add("| model | f | R_seq harmful EN | R_seq harmful SL | R_seq>0 harmful EN % | R_seq>0 harmful SL % | marker refusal of 48 harmful gens EN % | SL % | KL1 harmless median EN | SL | rep4 EN/SL | malformed EN/SL % |")
    add("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for m in MODELS:
        p = C.RES / "dose" / f"dose_{m}.json"
        if not p.exists():
            continue
        d = jload(p)
        for fct, v in d["per_factor"].items():
            add(f"| {NAME[m]} | {fct} | {f(v['R_seq_mean|en|harmful'], 2)} | {f(v['R_seq_mean|sl|harmful'], 2)} | {pc(v['R_seq_pos_frac|en|harmful'])} | {pc(v['R_seq_pos_frac|sl|harmful'])} | "
                f"{pc(v['gen_marker_refusal|en'])} | {pc(v['gen_marker_refusal|sl'])} | {f(v['KL1_harmless_median|en'], 4)} | {f(v['KL1_harmless_median|sl'], 4)} | "
                f"{f(v['gen_rep4_mean|en'], 2)}/{f(v['gen_rep4_mean|sl'], 2)} | {pc(v['gen_malformed_rule|en'])}/{pc(v['gen_malformed_rule|sl'])} |")
        if "judge2" in d:
            add(f"\n{NAME[m]} dose generations, second-judge labels: " + json_short(d["judge2"]))
    # ---------------- base
    bp = C.RES / "base_diag" / "base_diag.json"
    if bp.exists():
        b = jload(bp)
        a = b["at_layer34"]
        add("\n## T13 BONUS cjvt/GaMS3-12B base (pre-instruction diagnostic; descriptive)\n")
        add(f"- format `{b['format']!r}`, last prompt token; layer 34: frozen S3->S4 DiM AUROC EN {f(a['frozen_en'])} / SL {f(a['frozen_sl'])}; "
            f"grouped-CV S4 DiM AUROC EN {f(a['cv_en'])} / SL {f(a['cv_sl'])}; cos(base d_EN, base d_SL) {f(a['cos_base_dEN_dSL'])}; "
            f"nominal cos(base d_EN, Instruct d_EN) {f(a['cos_base_dEN_instruct_dEN'])}.")
        add(f"- best frozen layer EN L{b['best_layer_frozen_en']} ({f(b['max_frozen_en'])}), SL L{b['best_layer_frozen_sl']} ({f(b['max_frozen_sl'])}).")
        add(f"- 20 EN + 20 SL harmful continuations, gpt-4.1 labels: {b.get('judge_labels')}; marker refusal {b.get('marker_refusal_rate')} (NOT comparable to chat models).")
    (C.RES / "analysis" / "tables.md").write_text("\n".join(L) + "\n")
    print(f"wrote results/analysis/tables.md ({len(L)} lines)")


def json_short(x) -> str:
    import json

    return json.dumps(x)[:600]


if __name__ == "__main__":
    main()
